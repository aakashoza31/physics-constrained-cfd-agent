#!/usr/bin/env bash
# Reproduce nozzle/geometry_variation. Replay by default; --live re-executes OpenFOAM.
set -euo pipefail
cd "$(dirname "$0")/../../.."
MODE=replay
EXTRA=()
if [[ "${1:-}" == "--live" ]]; then
  MODE=live
  EXTRA+=(--i-want-to-run-cfd)
fi
python3 scripts/run_demo.py --family nozzle --case geometry_variation --mode "$MODE" "${EXTRA[@]}"
